const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  const page=await browser.newPage({viewport:{width:736,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8767/seed-requirement-picker-browser.html');
  const frame=page.frames().find(f=>f.parentFrame());
  const root=frame.locator('#seed-choice-picker');
  await root.waitFor();
  assert.equal(await root.locator('input[data-key^="s-"]').count(),22);
  assert.equal(await root.locator('input[data-key^="b-"]').count(),66);
  assert.equal(await frame.locator('#seed-count-s-village').inputValue(),'3');
  assert.equal(await frame.locator('#seed-choice-s-stronghold').isDisabled(),true);
  await frame.locator('#seed-count-s-village').fill('5');
  assert.match(await frame.locator('#seed-selection-text').inputValue(),/Village \(village\): at least 5/);
  await frame.locator('#seed-choice-s-village').uncheck();
  assert.equal(await frame.locator('#seed-count-s-village').isDisabled(),true);
  assert.doesNotMatch(await frame.locator('#seed-selection-text').inputValue(),/Village \(village\)/);
  await frame.locator('#seed-count-f-forest').fill('7');
  assert.equal(await frame.locator('#seed-copy').isDisabled(),true);
  await frame.locator('#seed-count-f-forest').fill('4');
  await frame.locator('#seed-choice-b-27').check();
  assert.match(await frame.locator('#seed-selection-text').inputValue(),/Forest \(forest\): at least 4 different types/);
  assert.match(await frame.locator('#seed-selection-text').inputValue(),/Birch Forest \(ID 27\)/);
  await frame.locator('#seed-choice-s-end_city').check();
  assert.match(await frame.locator('#seed-notes').textContent(),/End requirements need a search area/);
  await frame.locator('#seed-choice-s-end_city').uncheck();
  await frame.locator('#seed-count-s-desert_pyramid').fill('16');
  assert.match(await frame.locator('#seed-errors').textContent(),/share at most 16/);
  await frame.locator('#seed-count-s-desert_pyramid').fill('1');
  assert.equal(await frame.locator('#seed-copy').isEnabled(),true);
  await frame.locator('#seed-copy').focus();
  await page.waitForTimeout(150);
  await frame.locator('#seed-copy').click();
  await frame.waitForFunction(()=>document.querySelector('#seed-action-status').textContent.length>0);
  assert.match(await frame.locator('#seed-action-status').textContent(),/Copied|copy the text/);
  for(const width of [736,320]){
    await page.setViewportSize({width,height:1000});
    await frame.evaluate(()=>document.querySelectorAll('details').forEach(d=>d.open=true));
    const size=await frame.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth,height:document.documentElement.scrollHeight}));
    assert.ok(size.scroll<=size.client+1,JSON.stringify({width,...size}));
    await page.locator('iframe').evaluate((node,height)=>node.style.height=height+'px',size.height+20);
    await page.screenshot({path:'outputs/seed-requirement-picker-'+width+'.png',fullPage:true});
  }
  const hostPage=await browser.newPage();
  await hostPage.evaluate(()=>{window.saveCalls=0;window.openai={widgetState:{modelContent:{version:'seed-requirements-v1',structures:{stronghold:1,village:2},families:{forest:2},biomes:[27]}},setWidgetState:async value=>{window.saveCalls++;window.saved=value;},sendFollowUpMessage:async value=>{window.sent=value;}};});
  await hostPage.setContent(fs.readFileSync('outputs/seed-requirement-picker.html','utf8'));
  assert.equal(await hostPage.locator('#seed-count-s-village').inputValue(),'2');
  assert.equal(await hostPage.locator('#seed-choice-b-27').isChecked(),true);
  assert.equal(await hostPage.evaluate(()=>window.saveCalls),0);
  await hostPage.locator('#seed-count-s-village').fill('4');
  assert.equal(await hostPage.evaluate(()=>window.saved.modelContent.structures.village),4);
  await hostPage.locator('#seed-send').click();
  assert.match(await hostPage.evaluate(()=>window.sent.prompt),/Village \(village\): at least 4/);
  assert.match(await hostPage.evaluate(()=>window.sent.prompt),/Birch Forest \(ID 27\)/);
  await hostPage.evaluate(()=>window.dispatchEvent(new CustomEvent('openai:set_globals',{detail:{globals:{widgetState:{modelContent:{version:'seed-requirements-v1',structures:{stronghold:1},families:{},biomes:[21]}}}}})));
  assert.equal(await hostPage.locator('#seed-choice-b-21').isChecked(),true);
  assert.equal(await hostPage.locator('#seed-choice-s-village').isChecked(),false);
  assert.deepEqual(errors,[]);
  fs.writeFileSync('outputs/seed-requirement-picker-verification.json',JSON.stringify({catalog:{structures:22,biomes:66},counts:true,distinct_biome_semantics:true,shared_structure_validation:true,end_scope_warning:true,copy_fallback:true,host_send:true,saved_state_restore:true,state_event_restore:true,no_save_on_load:true,responsive_widths:[736,320],browser_errors:errors},null,2));
  console.log('Picker checks passed: catalog, counts, biome identities, constraints, copy fallback, 736px and 320px layouts.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
